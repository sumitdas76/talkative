"""Regenerate talkative/wordlist.py from the en_US Hunspell dictionary
(SCOWL size 60, https://wordlist.sourceforge.net).

Get index.dic and license from the npm package dictionary-en 4.0.0
(https://cdn.jsdelivr.net/npm/dictionary-en@4.0.0/), then:

    .venv\\Scripts\\python scripts\\make_wordlist.py <index.dic> <license>

Keeps the all-lowercase entries (no names, no acronyms): the ordinary
words continuation.py may lowercase at the start of a dictation typed
mid-sentence. Never hand-edit the output.
"""
import base64
import re
import sys
import zlib

dic, lic = sys.argv[1], sys.argv[2]
lines = open(dic, encoding="utf-8").read().splitlines()[1:]
words = sorted({w for w in (ln.split("/")[0] for ln in lines) if re.fullmatch(r"[a-z]+", w)})
blob = base64.b64encode(zlib.compress(" ".join(words).encode(), 9)).decode()
notice = open(lic, encoding="utf-8").read().replace("\\", "\\\\").replace('"""', "'''")
rows = [blob[i:i + 76] for i in range(0, len(blob), 76)]
with open("talkative/wordlist.py", "w", encoding="utf-8", newline="\n") as f:
    f.write('"""Ordinary English words (all-lowercase entries of the en_US Hunspell\n')
    f.write("dictionary, SCOWL size 60). Generated by scripts/make_wordlist.py --\n")
    f.write("do not edit. The dictionary's copyright and license follow.\n\n")
    f.write(notice.rstrip() + '\n"""\n\n')
    f.write("import base64 as _b64\nimport zlib as _zlib\n\n")
    f.write(f"COUNT = {len(words)}\n\n_DATA = (\n")
    for r in rows:
        f.write(f'    "{r}"\n')
    f.write(")\n\n\ndef load():\n")
    f.write('    """The word list as a frozenset (built on first use)."""\n')
    f.write("    return frozenset(_zlib.decompress(_b64.b64decode(_DATA)).decode().split())\n")
print(len(words), "words,", len(blob), "bytes")
